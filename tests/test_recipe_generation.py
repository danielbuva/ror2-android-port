"""Config generation contracts, using isolated synthetic work and public recipes only."""

import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts/lab"))
import build
import whole_catalog
from common import write


class RecipeGenerationTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.work = self.root / "work"
        for name, value in (("assert_build_unblocked", lambda: None), ("HOST_BUILD_LOCK", self.root / "unity-build.lock")):
            patcher = patch("build_lock." + name, value)
            patcher.start()
            self.addCleanup(patcher.stop)
        self.project = self.work / "lab-project"
        self.recipes = self.root / "recipe"
        self.targets = {
            "runtime-config.json": self.project / "Assets/LabLoadingScene/Resources/MovementBatchProbe.json",
            "content.json": self.work / "scene-probe-build.json",
        }
        self.value = {"z": ["Assets/Case.prefab", "assets/case.prefab", "Assets/Case.prefab"], "a": {"flag": True, "n": 3, "f": 3.0, "empty": ""}}
        for name in self.targets:
            write(self.recipes / name, self.value)
        for module, name, value in [(build, "RECIPE", self.recipes), (build, "WORK", self.work), (whole_catalog, "WORK", self.work)]:
            patcher = patch.object(module, name, value)
            patcher.start()
            self.addCleanup(patcher.stop)

    def generate(self):
        build.generate_runtime_config(self.project)
        build.generate_content_recipe()

    def snapshot(self):
        return {path.relative_to(self.root): path.read_bytes() for path in self.root.rglob("*") if path.is_file()}

    def test_deterministic_idempotent_exact_values_and_no_legacy_keys(self):
        for path in self.targets.values():
            write(path, {"obsolete": "discard", "a": False})
        self.generate()
        before = self.snapshot()
        expected = (json.dumps(self.value, indent=2, sort_keys=True) + "\n").encode()
        for path in self.targets.values():
            self.assertEqual(path.read_bytes(), expected)
        # Recipe source whitespace and object order cannot affect generated bytes.
        for name in self.targets:
            (self.recipes / name).write_text(json.dumps(self.value, separators=(",", ":")))
        self.generate()
        for path in self.targets.values():
            self.assertEqual(path.read_bytes(), before[path.relative_to(self.root)])
        before = self.snapshot()
        self.generate()
        self.assertEqual(before, self.snapshot())

    def test_generation_passes_existing_validators(self):
        self.generate()
        build.validate_runtime_config(self.project)
        build.validate_content_recipe()

    def test_tracked_recipes_pass_existing_validators(self):
        with patch.object(build, "RECIPE", ROOT / "recipe"):
            self.generate()
            build.validate_runtime_config(self.project)
            build.validate_content_recipe()
            for name, path in self.targets.items():
                self.assertEqual(json.loads(path.read_text()), json.loads((ROOT / "recipe" / name).read_text()))

    def test_only_two_targets_are_touched(self):
        for path in [self.project / "Assets/keep.txt", Path(str(self.targets["runtime-config.json"]) + ".meta"), self.work / "keep.json"]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("leave unchanged\n")
        before = self.snapshot()
        self.generate()
        after = self.snapshot()
        for path, content in before.items():
            self.assertEqual(after[path], content)
        self.assertEqual(after.keys() - before.keys(), {path.relative_to(self.root) for path in self.targets.values()})

    def test_missing_recipe_fails_without_changing_target(self):
        for name, generate in [("runtime-config.json", lambda: build.generate_runtime_config(self.project)), ("content.json", build.generate_content_recipe)]:
            with self.subTest(recipe=name):
                write(self.targets[name], {"keep": True})
                (self.recipes / name).unlink()
                before = self.snapshot()
                with self.assertRaisesRegex(RuntimeError, "Cannot read recipe/" + name):
                    generate()
                self.assertEqual(before, self.snapshot())

    def test_invalid_recipe_fails_without_output(self):
        for value in ["not JSON", "[]", "{}"]:
            generators = [("runtime-config.json", lambda: build.generate_runtime_config(self.project)), ("content.json", build.generate_content_recipe)]
            for name, generate in generators:
                with self.subTest(recipe=name, value=value):
                    (self.recipes / name).write_text(value)
                    with self.assertRaises(RuntimeError):
                        generate()
                    self.assertFalse(self.targets[name].exists())

    def test_both_build_paths_generate_before_staging_validation(self):
        class StopBeforeBuild(Exception):
            pass

        for code_only in [False, True]:
            with self.subTest(code_only=code_only):
                for path in self.targets.values():
                    path.unlink(missing_ok=True)

                def validate(project):
                    self.assertEqual(project, self.project)
                    build.validate_runtime_config(project)
                    build.validate_content_recipe()
                    raise StopBeforeBuild

                with patch.object(build, "build_source_identity", return_value={"commit": "fixture-commit"}), patch.object(
                    build, "validate_runtime_source_membership", side_effect=validate
                ), patch.object(build, "build") as invoke:
                    with self.assertRaises(StopBeforeBuild):
                        whole_catalog.build_integration(code_only=code_only)
                    invoke.assert_not_called()


if __name__ == "__main__":
    unittest.main()
