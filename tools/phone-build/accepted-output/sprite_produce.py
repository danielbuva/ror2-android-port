"""Prepare native Sprite inputs from original bundles, then emit checked records.

Preparation uses the existing public Texture2D decoder. The explicitly supplied
runtime constructor output is generated by SpriteNativeFixture on the exact SDK.
No exported image, original installation mutation or accepted body is required.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path
import struct
import time
import zlib

import importlib.util


def module(name):
    spec = importlib.util.spec_from_file_location("_sprites_" + name, Path(__file__).with_name(name + ".py"))
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


N, T = module("sprite_native_record"), module("texture_produce")
A = N.A
B, W, M = A.B, A.W, A.M


def png_rgba(rgba, width, height):
    """Encode logical bottom-up RGBA as a lossless, top-down PNG."""
    if not 0 < width <= 8192 or not 0 < height <= 8192 or len(rgba) != width * height * 4:
        raise ValueError("Invalid original RGBA image extent")

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    stride = width * 4
    scanlines = b"".join(b"\0" + rgba[row * stride : (row + 1) * stride] for row in range(height - 1, -1, -1))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(scanlines))
        + chunk(b"IEND", b"")
    )


def profile(path, pin):
    if B.sha(path) != pin:
        raise ValueError("Sprite profile drift")
    value = json.loads(path.read_text())
    if value["schema"] != 1 or value["input_id"] != M.INPUT_ID:
        raise ValueError("Unqualified Sprite source input")
    identities = [row["id"] for bundle in value["bundles"] for member in bundle["members"] for row in member["objects"]]
    if not identities or len(identities) != len(set(identities)):
        raise ValueError("Sprite source identities must be nonempty and unique")
    return value


def new_output(output, pc):
    output, pc = Path(output), Path(pc).resolve(strict=True)
    if output.exists() or output.is_symlink() or output.resolve().is_relative_to(pc) or pc.is_relative_to(output.resolve()):
        raise ValueError("New Sprite output outside original input required")
    output.mkdir()


def original_records(value, pc):
    """Yield source bodies/schema and a checked same-member Texture2D supplier."""
    pc = Path(pc).resolve(strict=True)
    for selected_bundle in value["bundles"]:
        path = M.safe_input(pc, selected_bundle["path"])
        before = path.stat()
        if B.sha(path) != selected_bundle["sha256"]:
            raise ValueError("Original Sprite bundle drift")
        bundle = B.Bundle(path)
        for selected_member in selected_bundle["members"]:
            stream = bundle.member(selected_member["name"])
            metadata = W.read_serialized(stream)
            objects = {row["path_id"]: row for row in metadata["objects"]}

            def read(selected, class_id):
                obj = objects[selected["path_id"]]
                typ = metadata["types"][obj["type_id"]]
                if typ["class_id"] != class_id:
                    raise ValueError("Original Sprite/Texture2D class drift")
                stream.seek(metadata["data_offset"] + obj["offset"])
                body = B.exact(stream, obj["bytes"])
                if hashlib.sha256(body).hexdigest() != selected["sha256"]:
                    raise ValueError("Original Sprite/Texture2D body drift")
                return body, A.SCHEMA.type_tree(io.BytesIO(typ["tree"]))

            for selected in selected_member["objects"]:
                body, root = read(selected, 213)
                _, spans = A.fields(body, root)
                start, end = spans[("m_RD", "texture")]
                if end - start != 12 or struct.unpack_from("<iq", body, start) != (0, selected["texture"]["path_id"]):
                    raise ValueError("Original Sprite texture relationship drift")
                texture, texture_root = read(selected["texture"], 28)
                yield selected, body, root, texture, texture_root, bundle
        after = path.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns) or B.sha(path) != selected_bundle["sha256"]:
            raise ValueError("Original Sprite input changed during production")


def source_pixels(texture, root, bundle, decoder):
    _, spans = A.fields(texture, root)

    def raw(path):
        start, end = spans[path]
        return texture[start:end]

    width = struct.unpack("<i", raw(("m_Width",)))[0]
    height = struct.unpack("<i", raw(("m_Height",)))[0]
    fmt = struct.unpack("<i", raw(("m_TextureFormat",)))[0]
    data = raw(("image data",))
    size = struct.unpack_from("<I", data)[0]
    pixels = data[4 : 4 + size]
    if not size:
        offset = struct.unpack("<Q", raw(("m_StreamData", "offset")))[0]
        # Unity's shared type-tree string table labels `size` with offset795.
        size_path = ("m_StreamData", "size") if ("m_StreamData", "size") in spans else ("m_StreamData", "#795")
        size = struct.unpack("<I", raw(size_path))[0]
        data = raw(("m_StreamData", "path"))
        length = struct.unpack_from("<I", data)[0]
        member = data[4 : 4 + length].decode("utf-8").split("/")[-1]
        stream = bundle.member(member)
        stream.seek(offset)
        pixels = B.exact(stream, size)
    if fmt in (3, 4, 9):
        pixels = pixels[: width * height * {3: 3, 4: 4, 9: 2}[fmt]]
    return T.source_rgba(pixels, width, height, fmt, {"pixels": str(decoder)}), width, height


def prepare(profile_path, profile_pin, pc, decoder, decoder_pin, output):
    value = profile(profile_path, profile_pin)
    if B.sha(decoder) != decoder_pin:
        raise ValueError("Public Sprite pixel decoder drift")
    new_output(output, pc)
    receipt = {"success": False, "input_id": M.INPUT_ID, "profile_sha256": profile_pin, "decoder_sha256": decoder_pin}
    try:
        items, pixels = [], []
        for selected, body, root, texture, texture_root, bundle in original_records(value, pc):
            rgba, width, height = source_pixels(texture, texture_root, bundle, decoder)
            path = output / (str(len(items)) + ".png")
            path.write_bytes(png_rgba(rgba, width, height))
            parameters = N.source_parameters(body, root)
            _, spans = A.fields(body, root)
            # The constructor keeps the original border; import recovery belongs
            # to the record assembler, as in the qualified runtime fixture.
            start, _ = spans[("m_Border",)]
            parameters["border"] = struct.unpack_from("<4f", body, start)
            extrude = struct.unpack_from("<I", body, spans[("m_Extrude",)][0])[0]
            settings = struct.unpack_from("<I", body, spans[("m_RD", "settingsRaw")][0])[0]
            items.append(dict(id=selected["id"], png=str(path.resolve()), sha256=B.sha(path), **parameters, extrude=extrude, mesh_type=(settings >> 6) & 1))
            pixels.append(dict(id=selected["id"], width=width, height=height, rgba_sha256=hashlib.sha256(rgba).hexdigest()))
        request = output / "sprite-source-request.json"
        request.write_text(json.dumps({"items": items}, indent=2) + "\n")
        if B.sha(profile_path) != profile_pin or B.sha(decoder) != decoder_pin:
            raise ValueError("Sprite preparation provider changed")
        receipt.update(success=True, items=len(items), request_sha256=B.sha(request), pixels=pixels)
        return receipt
    except Exception as error:
        receipt["error"] = type(error).__name__ + ": " + str(error)
        raise
    finally:
        (output / "result.json").write_text(json.dumps(receipt, indent=2) + "\n")


def produce(profile_path, profile_pin, pc, native_path, native_pin, output):
    value = profile(profile_path, profile_pin)
    if B.sha(native_path) != native_pin:
        raise ValueError("Native Sprite constructor output drift")
    native = json.loads(native_path.read_text())
    if native.get("success") is not True or native.get("unity_version") != "2021.3.45f2":
        raise ValueError("Exact SDK native Sprite output required")
    results = {row["id"]: row for row in native["items"]}
    required = {row["id"] for bundle in value["bundles"] for member in bundle["members"] for row in member["objects"]}
    if len(results) != len(native["items"]) or set(results) != required:
        raise ValueError("Native Sprite output does not cover the selected source cohort")
    new_output(output, pc)
    started = time.monotonic()
    receipt = {"success": False, "input_id": M.INPUT_ID, "profile_sha256": profile_pin, "native_sha256": native_pin, "objects": 0, "object_bytes": 0}
    try:
        with (output / "objects.bin").open("xb") as data, (output / "index.jsonl").open("x") as index:
            for selected, body, root, _, _, _ in original_records(value, pc):
                made = N.assemble(body, root, results[selected["id"]], selected["importer_guid"])
                for target in selected["outputs"]:
                    result = A.O.remap(made, target["references"])
                    if len(result) != target["bytes"] or hashlib.sha256(result).hexdigest() != target["sha256"]:
                        raise ValueError("Produced Sprite record differs from accepted hash")
                    row = {key: target[key] for key in ("bundle", "member", "path_id", "bytes", "sha256")}
                    row["offset"] = data.tell()
                    data.write(result)
                    index.write(json.dumps(row, sort_keys=True) + "\n")
                    receipt["objects"] += 1
                    receipt["object_bytes"] += len(result)
        with (output / "objects.bin").open("rb") as data, (output / "index.jsonl").open() as index:
            for line in index:
                row = json.loads(line)
                data.seek(row["offset"])
                if hashlib.sha256(B.exact(data, row["bytes"])).hexdigest() != row["sha256"]:
                    raise ValueError("Persisted Sprite record extent drift")
        if B.sha(profile_path) != profile_pin or B.sha(native_path) != native_pin:
            raise ValueError("Sprite production provider changed")
        receipt.update(
            success=True, outputs={name: {"bytes": (output / name).stat().st_size, "sha256": B.sha(output / name)} for name in ("objects.bin", "index.jsonl")}
        )
        return receipt
    except Exception as error:
        receipt["error"] = type(error).__name__ + ": " + str(error)
        raise
    finally:
        receipt["seconds"] = time.monotonic() - started
        (output / "result.json").write_text(json.dumps(receipt, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "produce"), help="Current source-pixel preparation or qualified native record-pack production")
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--profile-sha256", required=True)
    parser.add_argument("--pc-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--pixels-tool", type=Path)
    parser.add_argument("--pixels-sha256")
    parser.add_argument("--native-output", type=Path)
    parser.add_argument("--native-sha256")
    args = parser.parse_args()
    if args.action == "prepare":
        if args.pixels_tool is None or args.pixels_sha256 is None:
            parser.error("prepare requires an explicit public pixel decoder and hash")
        result = prepare(args.profile, args.profile_sha256, args.pc_root, args.pixels_tool, args.pixels_sha256, args.output)
    else:
        if args.native_output is None or args.native_sha256 is None:
            parser.error("produce requires explicit exact-SDK constructor output and hash")
        result = produce(args.profile, args.profile_sha256, args.pc_root, args.native_output, args.native_sha256, args.output)
    print(json.dumps(result))


if __name__ == "__main__":
    main()
